import numpy as np
import pandas as pd

# Make results reproducible
np.random.seed(42)

# Generate 500 synthetic pineapple farm observations
n = 600

temperature = np.random.uniform(20, 36, n)
humidity = np.random.uniform(45, 100, n)
soil_moisture = np.random.uniform(15, 90, n)
rainfall = np.random.gamma(shape=2.0, scale=12.0, size=n)
rainfall = np.clip(rainfall, 0, 100)
soil_ph = np.random.uniform(3.5, 7.5, n)

# Build a simulated disease-risk score.
# Higher humidity, wet soil, rainfall, and warm conditions
# can contribute to elevated risk in this dataset.
risk_score = (
    0.025 * (humidity - 70)
    + 0.035 * (soil_moisture - 50)
    + 0.025 * (rainfall - 20)
    + 0.10 * np.maximum(temperature - 28, 0)
    + 0.08 * np.maximum(soil_ph - 5.5, 0)
    + np.random.normal(0, 0.65, n)
)

# Label the observations as low risk (0) or high risk (1)
disease_risk = (risk_score > 0.45).astype(int)

# Create the dataset with exactly five features and one target
df = pd.DataFrame({
    "temperature_c": temperature.round(2),
    "humidity_pct": humidity.round(2),
    "soil_moisture_pct": soil_moisture.round(2),
    "rainfall_mm": rainfall.round(2),
    "soil_ph": soil_ph.round(2),
    "disease_risk": disease_risk
})

# Save and download the dataset as a CSV file
from google.colab import files
df.to_csv("pineapple_disease_risk.csv", index=False)
files.download("pineapple_disease_risk.csv")

print("Dataset saved and downloaded successfully!")
print(f"Shape: {df.shape[0]} rows, {df.shape[1]} columns")
print("\nFirst 5 rows:")
display(df.head())